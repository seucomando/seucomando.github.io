// Código de barras Code 39 em SVG (legível por leitores comuns). Sem dependências.
(function (g) {
  'use strict';
  var T = {'0':'000110100','1':'100100001','2':'001100001','3':'101100000','4':'000110001','5':'100110000','6':'001110000','7':'000100101','8':'100100100','9':'001100100','A':'100001001','B':'001001001','C':'101001000','D':'000011001','E':'100011000','F':'001011000','G':'000001101','H':'100001100','I':'001001100','J':'000011100','K':'100000011','L':'001000011','M':'101000010','N':'000010011','O':'100010010','P':'001010010','Q':'000000111','R':'100000110','S':'001000110','T':'000010110','U':'110000001','V':'011000001','W':'111000000','X':'010010001','Y':'110010000','Z':'011010000','-':'010000101','.':'110000100',' ':'011000100','*':'010010100'};
  function svg(text, h) {
    var s = '*' + String(text).toUpperCase().replace(/[^0-9A-Z\-. ]/g, '') + '*';
    var x = 10, n = 2, w = 5, rects = '';
    for (var i = 0; i < s.length; i++) {
      var p = T[s[i]];
      for (var k = 0; k < 9; k++) {
        var bw = p[k] === '1' ? w : n;
        if (k % 2 === 0) rects += '<rect x="' + x + '" y="0" width="' + bw + '" height="' + h + '"/>';
        x += bw;
      }
      x += n;
    }
    return '<svg viewBox="0 0 ' + (x + 10) + ' ' + h + '" preserveAspectRatio="none" role="img" aria-label="Código de barras ' + s.replace(/\*/g, '') + '"><g fill="#17211C">' + rects + '</g></svg>';
  }
  g.Code39 = { svg: svg };
})(window);
